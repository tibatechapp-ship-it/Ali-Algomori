def test_api_execute_and_report_endpoints(store):
    client = TestClient(app)
    from geologia.data_layer.certification import certify_engine
    certify_engine("porosity_density_v1")
    rec = client.post("/api/v1/datasets", json={
        "name": "سجل ذهبي", "path": str(DATA / "golden_las_valid.las"),
        "dtype": "las",
    }).json()
    client.post(f"/api/v1/datasets/{rec['id']}/validate")
    task = client.post("/api/v1/tasks", json={
        "title": "مسامية بئر اختبار", "engine_id": "porosity_density_v1",
        "dataset_ids": [rec["id"]],
        "isolation": {"pinned_version": "1.0.0", "cpu": 1, "memory_mb": 256,
                      "timeout_seconds": 60},
    }).json()
    client.post(f"/api/v1/tasks/{task['id']}/transition",
                json={"to_state": "inputs_validated"})
    r = client.post(f"/api/v1/tasks/{task['id']}/transition", json={"to_state": "ready"})
    assert r.status_code == 200
    r = client.post(f"/api/v1/tasks/{task['id']}/execute")
    assert r.status_code == 200
    assert r.json()["state"] == "executed"
    r = client.get(f"/api/v1/tasks/{task['id']}/report")
    assert r.status_code == 200
    body = r.json()
    assert body["method"]["citations"]
    assert "sigma_phi_vv" in body["uncertainty"]
    # a not-yet-executed task has no report — honest 404
    task2 = client.post("/api/v1/tasks", json={
        "title": "لم تُنفذ", "engine_id": "porosity_density_v1",
        "dataset_ids": [rec["id"]],
    }).json()
    r = client.get(f"/api/v1/tasks/{task2['id']}/report")
    assert r.status_code == 404
    assert r.json()["detail"]["error"] == "no_execution_report"
