def test_verified_requires_complete_evidence(store, tmp_path):
    from geologia.data_layer import tasks as tl
    t = _certified_task(store, tmp_path=tmp_path)
    tl.transition(t["id"], "inputs_validated")
    tl.transition(t["id"], "ready")
    t = tl.transition(t["id"], "executed")
    path = Path(t["execution_report_path"])
    report = json.loads(path.read_text(encoding="utf-8"))
    del report["uncertainty"]
    path.write_text(json.dumps(report, ensure_ascii=False), encoding="utf-8")
    with pytest.raises(tl.TaskGateError) as exc:
        tl.transition(t["id"], "verified")
    assert exc.value.gate == "evidence_incomplete"
    assert tl.get_task(t["id"])["state"] == "executed"


