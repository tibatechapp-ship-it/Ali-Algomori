def test_certify_refuses_third_party(store):
    from geologia.data_layer.certification import CertificationRefused, certify_engine
    with pytest.raises(CertificationRefused) as exc:
        certify_engine("gempy")
    assert any("third_party" in r for r in exc.value.reasons)
    assert any("ADR-0003" in r or "lifecycle" in r for r in exc.value.reasons)


def test_certify_unknown_engine_is_value_error(store):
    from geologia.data_layer.certification import certify_engine
    with pytest.raises(ValueError):
        certify_engine("ghost-engine")


def test_certify_first_party_passes_and_records(store):
    from geologia.data_layer.certification import certification_status, certify_engine
    r = certify_engine("porosity_density_v1")
    assert r["certified"] is True
    rec = r["record"]
    assert rec["passed"] is True
    assert rec["max_abs_error"] <= rec["tolerance"]
    assert rec["checked_rows"] == 6
    assert rec["citations"], "certification must record its provenance citations"
    status = certification_status("porosity_density_v1")
    assert status["certified"] is True
    assert (store / "certifications.json").exists()


def test_certification_is_repeatable_and_overwrites(store):
    from geologia.data_layer.certification import certify_engine
    certify_engine("porosity_density_v1")
    r = certify_engine("porosity_density_v1")
    assert r["certified"] is True
    data = json.loads((store / "certifications.json").read_text(encoding="utf-8"))
    assert len(data["certifications"]) == 1  # latest record replaces, not stacks


def test_reference_input_tamper_refuses_certification(store, monkeypatch, tmp_path):
    from geologia.data_layer import certification as cert
    tampered = tmp_path / "tampered.las"
    src = (DATA / "golden_las_valid.las").read_text(encoding="utf-8")
    tampered.write_text(src.replace("2.650", "2.600"), encoding="utf-8")
    monkeypatch.setattr(cert, "resolve_reference_input", lambda ref: tampered)
    with pytest.raises(cert.CertificationRefused) as exc:
        cert.certify_engine("porosity_density_v1")
    assert any("sha256" in r for r in exc.value.reasons)


