def test_engine_rejects_out_of_range_params(store):
    from geologia.engines.porosity_density import (
        PorosityEngineError,
        run_porosity_density,
    )
    src = str(DATA / "golden_las_valid.las")
    with pytest.raises(PorosityEngineError):
        run_porosity_density(src, {"rho_ma_gcm3": 3.0})
    with pytest.raises(PorosityEngineError):
        run_porosity_density(src, {"rho_fl_gcm3": 0.5})
    with pytest.raises(PorosityEngineError):
        run_porosity_density(src, {"sigma_rhob_gcm3": 1.0})


def test_engine_handles_null_rows_honestly(store, tmp_path):
    from geologia.engines.porosity_density import run_porosity_density
    src = (DATA / "golden_las_valid.las").read_text(encoding="utf-8")
    src = src.replace("101.000   2.640   0.152", "101.000   -999.25  0.152")
    f = tmp_path / "with_null.las"
    f.write_text(src, encoding="utf-8")
    out = run_porosity_density(str(f))
    row = next(r for r in out["results"] if r["depth_m"] == 101.0)
    assert row["porosity_vv"] is None and row["flag"] == "NULL_VALUE"
    codes = [i["code"] for i in out["issues"]]
    assert "NULL_VALUE" in codes


def test_engine_reports_negative_porosity_without_clamping(store):
    from geologia.engines.porosity_density import run_porosity_density
    out = run_porosity_density(str(DATA / "golden_las_valid.las"))
    neg = [r for r in out["results"] if r["flag"] == "NEGATIVE_POROSITY"]
    assert len(neg) == 2
    assert neg[0]["porosity_vv"] < 0  # raw value kept, never clamped
    assert out["issues"][0]["code"] == "NEGATIVE_POROSITY"


# ---------------------------------------------------------------------------
# Locked execution with execution-time tamper detection
# ---------------------------------------------------------------------------
def _certified_task(store, engine="porosity_density_v1", src="golden_las_valid.las",
                    tmp_path=None):
    from geologia.data_layer import records as ds, tasks as tl
    from geologia.data_layer.certification import certify_engine
    certify_engine(engine)
    # Register a COPY of the golden input inside the store area: tamper tests
    # must never touch the repository's golden fixture files.
    work = (tmp_path or store) / "work"
    work.mkdir(parents=True, exist_ok=True)
    local = work / src
    local.write_bytes((DATA / src).read_bytes())
    rec = ds.register_dataset("سجل ذهبي", str(local), dtype="las")
    ds.validate_dataset(rec["id"])
    return tl.create_task(
        "تنفيذ مرجعي", engine, [rec["id"]],
        isolation={"pinned_version": "1.0.0", "cpu": 1, "memory_mb": 256,
                   "timeout_seconds": 60})


def test_full_pipeline_reaches_verified(store, tmp_path):
    from geologia.data_layer import tasks as tl
    t = _certified_task(store, tmp_path=tmp_path)
    t = tl.transition(t["id"], "inputs_validated")
    t = tl.transition(t["id"], "ready")
    assert t["state"] == "ready"
    t = tl.transition(t["id"], "executed")
    assert t["state"] == "executed"
    assert t["execution_summary"]["n_results"] == 6
    assert "NEGATIVE_POROSITY" in t["execution_summary"]["issue_codes"]
    t = tl.transition(t["id"], "verified")
    assert t["state"] == "verified"
    report = json.loads(Path(t["execution_report_path"]).read_text(encoding="utf-8"))
    assert report["method"]["citations"]
    assert report["uncertainty"]["sigma_phi_vv"] == pytest.approx(1 / 110, rel=1e-9)
    assert all(i["checksum_verified_at_execution"] for i in report["inputs"])
    assert report["validity_limits_ar"] and report["disclaimers_ar"]


def test_execution_tamper_stops_run(store, tmp_path):
    from geologia.data_layer import records as ds, tasks as tl
    t = _certified_task(store, tmp_path=tmp_path)
    tl.transition(t["id"], "inputs_validated")
    tl.transition(t["id"], "ready")
    rec = ds.get_dataset(t["dataset_ids"][0])
    Path(rec["path"]).write_text("tampered bytes", encoding="utf-8")
    with pytest.raises(tl.TaskGateError) as exc:
        tl.transition(t["id"], "executed")
    assert exc.value.gate == "data_tamper"
    assert tl.get_task(t["id"])["state"] == "ready"  # state did not flip


